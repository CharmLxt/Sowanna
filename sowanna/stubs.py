"""Генератор .pyi стабов для Sowanna-манифеста."""
from pathlib import Path

from .manifest import Manifest


_CSHARP_TO_PYTHON = {
    "int": "int", "int32": "int", "int64": "int", "long": "int",
    "short": "int", "int16": "int", "byte": "int", "sbyte": "int",
    "uint": "int", "uint32": "int", "uint64": "int", "ulong": "int",
    "ushort": "int",
    "float": "float", "double": "float", "single": "float", "decimal": "float",
    "string": "str", "String": "str", "char": "str",
    "bool": "bool", "Boolean": "bool",
    "void": "None", "Void": "None",
    "object": "Any", "Object": "Any", "dynamic": "Any",
    "task": "Any", "Task": "Any",
}


def _map_type(t):
    if not t:
        return "Any"
    s = str(t).strip()
    if s.endswith("[]"):
        inner = _map_type(s[:-2])
        return f"List[{inner}]"
    if s.endswith("?"):
        inner = _map_type(s[:-1])
        return f"Optional[{inner}]"
    if s in _CSHARP_TO_PYTHON:
        return _CSHARP_TO_PYTHON[s]
    lower = s.lower()
    if lower in _CSHARP_TO_PYTHON:
        return _CSHARP_TO_PYTHON[lower]
    return "Any"


def _collect_type_tokens(py_type, out_set):
    for token in py_type.replace("[", " ").replace("]", " ").replace(",", " ").split():
        out_set.add(token)


def _build_typing_import(used):
    keep = []
    for name in ("Any", "List", "Optional", "Union", "Dict"):
        if name in used:
            keep.append(name)
    if not keep:
        keep = ["Any"]
    return f"from typing import {', '.join(keep)}"


def generate_stubs(manifest, class_name=None):
    """Возвращает содержимое .pyi как строку."""
    if isinstance(manifest, (str, Path)):
        manifest = Manifest.from_file(manifest)
    if not isinstance(manifest, Manifest):
        raise TypeError(
            f"manifest должен быть Manifest или путь, "
            f"получено {type(manifest).__name__}"
        )

    if class_name is None:
        class_name = manifest.entry_class.split(".")[-1] or "SowannaModule"

    header = [
        f'"""Auto-generated by Sowanna for manifest {manifest.name} v{manifest.version}.',
        f'Entry class: {manifest.entry_class}',
        f'Do not edit manually. Regenerate with: sowanna stubs <manifest>"""',
        "",
    ]

    used_types = set()
    body = []

    if manifest.methods:
        for name, spec in sorted(manifest.methods.items()):
            args_parts = []
            for i, arg_type in enumerate(spec.args):
                arg_py = _map_type(arg_type)
                _collect_type_tokens(arg_py, used_types)
                args_parts.append(f"arg{i}: {arg_py}")

            ret_py = _map_type(spec.returns) if spec.returns else "Any"
            _collect_type_tokens(ret_py, used_types)

            body.append("    @staticmethod")
            sig = f"    def {name}({', '.join(args_parts)}) -> {ret_py}:"
            if spec.description:
                body.append(sig)
                body.append(f'        """{spec.description}"""')
                body.append("        ...")
            else:
                body.append(sig + " ...")
            body.append("")
    else:
        body.append("    ...")
        body.append("")

    lines = header[:]
    lines.append(_build_typing_import(used_types))
    lines.append("")
    lines.append("")
    lines.append(f"class {class_name}:")
    lines.extend(body)
    return "\n".join(lines).rstrip() + "\n"


def write_stubs(manifest, output=None, class_name=None):
    """Сохраняет .pyi. Если output=None — рядом с манифестом."""
    if isinstance(manifest, (str, Path)):
        manifest = Manifest.from_file(manifest)
    content = generate_stubs(manifest, class_name=class_name)

    if output is None:
        if manifest.manifest_path is None:
            raise ValueError("Не указан output и у манифеста нет пути")
        output = manifest.manifest_path.with_suffix(".pyi")

    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, "utf-8")
    return output


__all__ = ["generate_stubs", "write_stubs"]